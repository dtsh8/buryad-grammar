#!/usr/bin/env node
// ─── audio.ts ─────────────────────────────────────────────────────────────
// Pronunciation clips: scans public/audio/ and
//   • writes public/audio/manifest.json — the app shows a play button for these words only;
//   • writes docs/audio-checklist.md — every word with a play button slot, recorded or not;
//   • warns about files that match no word (usually a typo in the file name).
//
//   npm run audio
//
// Run it after adding, renaming or removing a clip, and commit the clip, the manifest and
// the checklist together. The Vitest suite fails if the manifest is out of date.

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { buildManifest, AUDIO_EXTENSIONS } from '../src/utils/audio.ts';
import { audioInventory, type InventoryItem } from '../src/utils/audioInventory.ts';
import type { VocabularyData } from '../src/data/vocabulary.types.ts';

const ROOT = new URL('..', import.meta.url);
const AUDIO_DIR = new URL('public/audio/', ROOT);

mkdirSync(AUDIO_DIR, { recursive: true });
const manifest = buildManifest(readdirSync(AUDIO_DIR));
writeFileSync(new URL('manifest.json', AUDIO_DIR), JSON.stringify(manifest, null, 2) + '\n');

const vocabulary = (
  JSON.parse(readFileSync(new URL('public/data/vocabulary.json', ROOT), 'utf8')) as VocabularyData
).entries;
const inventory = audioInventory(vocabulary);
const known = new Set(inventory.map(i => i.key));
const recorded = inventory.filter(i => manifest.clips[i.key]);

// ─── Checklist ────────────────────────────────────────────────────────────

const sections = new Map<string, InventoryItem[]>();
for (const item of inventory) {
  const section = item.where[0].split(' · ')[0];
  sections.set(section, [...(sections.get(section) ?? []), item]);
}

const escape = (s: string) => s.replace(/\|/g, '\\|');
const lines = [
  '# Pronunciation recording checklist',
  '',
  '<!-- Generated by `npm run audio`. Do not edit by hand. -->',
  '',
  `**${recorded.length} of ${inventory.length} recorded.**`,
  '',
  'How to add a recording:',
  '',
  '1. Record one word per file, a native speaker at a natural pace, with about half a second of silence before and after.',
  `2. Name the file after the word, exactly as in the "File" column, with the extension .mp3 or .m4a (also accepted: ${AUDIO_EXTENSIONS.join(', ')}). Upper case is fine.`,
  '3. Put it in `public/audio/` and run `npm run audio`. The word gets a play button everywhere it appears.',
  '',
];
for (const [section, items] of sections) {
  const done = items.filter(i => manifest.clips[i.key]).length;
  lines.push(`## ${section} (${done}/${items.length})`, '');
  lines.push('| | Word | File | Meaning | Shown in |', '|---|---|---|---|---|');
  for (const i of items) {
    lines.push(
      `| ${manifest.clips[i.key] ? '✅' : '⬜'} | ${escape(i.word)} | \`${i.key}\` | ${escape(i.gloss)} | ${i.where.join('; ')} |`
    );
  }
  lines.push('');
}
writeFileSync(new URL('docs/audio-checklist.md', ROOT), lines.join('\n'));

// ─── Report ───────────────────────────────────────────────────────────────

console.log(`${recorded.length} of ${inventory.length} words recorded.`);
const strays = Object.entries(manifest.clips).filter(([key]) => !known.has(key));
for (const [key, file] of strays) {
  console.warn(
    `⚠ public/audio/${file} matches no word in the app (key "${key}"). Check the spelling.`
  );
}
